//! Literal header projections of the reviewed S1.1 exchange specifications.
//!
//! Expected values are fixed protocol facts, not production decoder output.
//! Fixture context for later exchange admission is deliberately outside this crate.

/// Exact inert field values for one decoded header.
#[derive(Clone, Copy)]
pub(super) struct ExpectedHeader {
    /// Raw leap, version and mode subfields, including nonsemantic values.
    pub(super) flags: (u8, u8, u8),
    /// Raw stratum octet.
    pub(super) stratum: u8,
    /// Signed two's-complement polling exponent.
    pub(super) poll: i8,
    /// Signed two's-complement precision exponent.
    pub(super) precision: i8,
    /// Uninterpreted network-order root-delay bits.
    pub(super) root_delay: u32,
    /// Uninterpreted network-order root-dispersion bits.
    pub(super) root_dispersion: u32,
    /// Uninterpreted network-order reference identifier.
    pub(super) reference_id: u32,
    /// Reference, origin, receive and transmit timestamp bits in that order.
    pub(super) timestamps: [u64; 4],
}

/// One complete literal input and its independently specified header outcome.
pub(super) struct HeaderCase {
    /// Stable source-specification case name for assertion diagnostics.
    pub(super) name: &'static str,
    /// Literal wire octets, including short and long rejection neighbors.
    pub(super) packet: &'static [u8],
    /// Literal raw fields, or exact-length rejection when absent.
    pub(super) expected: Option<ExpectedHeader>,
}

