/// Raw literal fixture row; legitimate product construction remains unavoidable.
#[derive(Clone, Copy)]
pub(super) struct RawRow {
    /// Asserted source/frame/generation labels, each nonzero.
    pub(super) context: [u64; 3],
    /// Exact supplied monotonic reading, including readings near `u64::MAX`.
    pub(super) observed_ns: u64,
    /// Exact numerator created through four UTC coordinates and exchange arithmetic.
    pub(super) phase_q33: i128,
    /// Exact caller divisor bits, preserving either zero sign and invalid classes.
    pub(super) divisor_bits: u64,
}

/// Independent semantic outcome names, never implementation-derived error strings.
#[derive(Clone, Copy)]
pub(super) enum Kind {
    /// Held prepared input with literal chronological point bits.
    Prepared,
    /// Typed count 0..2 payload with an optional real newest reference.
    Insufficient,
    /// Narrow phase rejection before any divisor error.
    ObservationPhase,
    /// Nonfinite divisor rejection.
    ObservationNonFinite,
    /// Subnormal divisor rejection before range.
    ObservationSubnormal,
    /// Finite normal-or-zero divisor outside [1/16,16].
    ObservationRange,
    /// More than 64 checked observations, before element admission.
    Count,
    /// First mismatched explicit context.
    Context,
    /// Later member of the first non-increasing integer-time pair.
    Order,
    /// First elapsed window over the exact maximum.
    Elapsed,
    /// Prepared count with insufficient oldest exact elapsed span.
    Span,
    /// Actual computed parent geometry below 1/256.
    Spread,
}

/// One frozen named ordinary set, with at most65 raw rows.
