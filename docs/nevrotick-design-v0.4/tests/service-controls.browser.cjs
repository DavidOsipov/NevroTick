'use strict';
// Deterministic HTML-only examples; HTTP is local artifact delivery, not product IPC.
const {chromium}=require('playwright');
const http=require('node:http');
const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const screenshotDir=process.env.SERVICE_SCREENSHOT_DIR;
(async()=>{
  const server=http.createServer((req,res)=>{
    const file=path.join(root,decodeURIComponent(new URL(req.url,'http://localhost').pathname));
    if(!file.startsWith(root+path.sep)) return res.writeHead(403).end();
    try{res.end(fs.readFileSync(file));}catch{res.writeHead(404).end();}
  });
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
  const results=[];
  try{
    for(const file of ['index.html','NevroTick-UI-v0.4.html']) for(const width of [360,1280]){
      const page=await browser.newPage({viewport:{width,height:1000}});
      const errors=[],external=[];
      page.on('pageerror',e=>errors.push(e.message));
      page.on('request',req=>{if(!req.url().startsWith('http://127.0.0.1:')&&!req.url().startsWith('data:'))external.push(req.url());});
      const openSettings=async()=>{
        await page.locator('.app-nav [data-value="settings"]').click();
        await page.locator('.settings-nav [data-value="service"]').click();
      };
      const response=page.locator('#service-response');
      const controls=()=>page.locator('#background-service [data-action="service-request"]');
      const operation=op=>page.locator(`#background-service [data-action="service-request"][data-value="${op}"]`);
      const choose=async value=>{
        if(!(await page.locator('#reviewer-controls').evaluate(e=>e.open)))await page.locator('#reviewer-controls > summary').click();
        await page.locator('#sample-service-response').selectOption(value);
      };
      const submit=async op=>{
        await operation(op).click();
        assert.equal(await page.locator('dialog select').count(),0);
        assert.match(await page.locator('dialog').innerText(),/Administrator required/);
        await page.locator('dialog [data-action="service-confirm"]').focus();
        await page.keyboard.press('Enter');
        assert.equal(await page.locator('dialog').count(),0);
        assert.match(await response.innerText(),/Pending/);
        assert.equal(await controls().evaluateAll(nodes=>nodes.every(n=>n.disabled)),true);
        assert.equal(await response.evaluate(e=>e===document.activeElement),true);
        const responseBox=await response.boundingBox();
        assert.ok(responseBox.y>=0&&responseBox.y+responseBox.height<=1001,'complete pending feedback is visible after keyboard confirmation');
        await page.keyboard.press('Tab');
        assert.equal(await page.evaluate(()=>Boolean(document.activeElement.closest('#background-service'))),true,'next Tab stays in the local service controls');
        await response.focus();
      };
      const deliver=async()=>page.getByRole('button',{name:'Deliver sample service response',exact:true}).click();
      await page.goto(`http://127.0.0.1:${server.address().port}/${file}`);
      await page.locator('.app-nav [data-value="settings"]').click();
      assert.match(await page.locator('.simple-service-summary').innerText(),/Closing the app does not change the service state/);
      assert.equal(await page.locator('.app-window [data-action="service-request"]').count(),0);
      await page.getByRole('button',{name:'Manage service in Power user',exact:true}).click();
      assert.equal(await controls().count(),3);
      assert.equal(await operation('start').isDisabled(),true);
      assert.equal(await operation('stop').isEnabled(),true);
      await page.locator('.app-nav [data-value="diagnostics"]').click();
      await page.getByRole('button',{name:'Preview temporary collection',exact:true}).click();
      await page.locator('#sample-log-scope').selectOption('both');
      await page.getByRole('button',{name:'Start example',exact:true}).click();
      assert.match(await page.locator('#sample-log-result').innerText(),/Sample response · Active/);
      await page.keyboard.press('Escape');
      await openSettings();
      await page.evaluate(()=>{window.originalResponse=document.getElementById('service-response');window.fixture=JSON.stringify(window.NevroTickModel.getScenario('healthy'));});
      const fixtureSnapshot=await page.evaluate(()=>window.fixture);
      await operation('stop').click();
      assert.match(await page.locator('dialog').innerText(),/clock may drift/);
      assert.match(await page.locator('dialog').innerText(),/Windows Time will not be enabled automatically/);
      await page.keyboard.press('Escape');
      assert.equal(await operation('stop').evaluate(e=>e===document.activeElement),true);
      assert.match(await response.innerText(),/Cancelled before submission/);
      await choose('uac-cancelled');
      await submit('stop');
      assert.equal(await page.evaluate(()=>window.originalResponse===document.getElementById('service-response')),true);
      await page.locator('.app-nav [data-value="status"]').click();
      assert.match(await page.locator('#state-title').innerText(),/pending/);
      assert.doesNotMatch(await page.locator('.status-summary').innerText(),/3 of 4 identities/);
      await openSettings();
      assert.match(await response.innerText(),/Pending/);
      await page.getByRole('button',{name:'Diagnose',exact:true}).click();
      assert.match(await page.locator('#service-diagnosis').innerText(),/Operation pending/);
      assert.match(await page.locator('.sample-log-summary').innerText(),/Unconfirmed/);
      assert.match(await page.locator('.sample-log-summary').innerText(),/Unknown · service response not received/);
      assert.equal(await page.locator('#service-diagnosis-title').evaluate(e=>e===document.activeElement),true);
      const evidenceBox=await page.locator('#service-diagnosis-title').boundingBox();
      assert.ok(evidenceBox.y>=0&&evidenceBox.y<1000);
      await page.getByRole('button',{name:'Back to Background service',exact:true}).click();
      await deliver();
      assert.match(await response.innerText(),/Administrator prompt cancelled/);
      assert.equal(await response.evaluate(e=>e===document.activeElement),true);
      assert.equal(await operation('stop').isEnabled(),true);
      await choose('failed'); await submit('restart'); await deliver();
      assert.match(await response.innerText(),/Request rejected/);
      assert.match(await page.locator('.service-facts').innerText(),/Both services running/);
      await choose('confirmed'); await submit('stop');
      await page.getByRole('button',{name:'Сбросить сцену и настройки',exact:true}).click();
      assert.match(await page.locator('dialog').innerText(),/Pending or unknown service examples/);
      await page.getByRole('button',{name:'Cancel',exact:true}).click();
      assert.match(await response.innerText(),/Pending/);
      await deliver();
      assert.match(await response.innerText(),/Stopped · confirmed sample/);
      assert.equal(await operation('start').isEnabled(),true);
      if(screenshotDir){fs.mkdirSync(screenshotDir,{recursive:true});await page.screenshot({path:path.join(screenshotDir,`${file.startsWith('index')?'local':'standalone'}-stopped-${width}.png`),fullPage:true});}
      await page.locator('.app-nav [data-value="status"]').click();
      assert.match(await page.locator('#state-title').innerText(),/Background service is stopped/);
      assert.doesNotMatch(await page.locator('main').innerText(),/Time sync active/);
      await page.locator('.app-nav [data-value="sources"]').click();
      assert.match(await page.locator('main').innerText(),/Historical source snapshot/);
      assert.match(await page.locator('main').innerText(),/18 s ago/);
      await page.locator('[data-action="source-details"][data-value="alpha"]').first().click();
      assert.match(await page.locator('dialog').innerText(),/Historical source evidence/);
      assert.match(await page.locator('dialog').innerText(),/NTS · prior evidence only/);
      await page.keyboard.press('Escape');
      await page.locator('.app-nav [data-value="statistics"]').click();
      assert.match(await page.locator('main').innerText(),/Historical source evidence/);
      await page.locator('.app-nav [data-value="diagnostics"]').click();
      assert.match(await page.locator('.sample-log-summary').innerText(),/Partial/);
      assert.match(await page.locator('.sample-log-summary').innerText(),/Prior session ended by service stop or restart/);
      await page.getByRole('button',{name:'Preview temporary collection',exact:true}).click();
      await page.getByRole('button',{name:'Stop example',exact:true}).click();
      await page.locator('#sample-log-scope').selectOption('service');
      assert.equal(await page.getByRole('button',{name:/^Start example/}).isDisabled(),true);
      await page.locator('#sample-log-scope').selectOption('both');
      await page.getByRole('button',{name:'Start example',exact:true}).click();
      assert.match(await page.locator('#sample-log-result').innerText(),/Sample response · Partial/);
      assert.match(await page.locator('#sample-log-result').innerText(),/service confirmed stopped/);
      await page.getByRole('button',{name:'Stop example',exact:true}).click();
      await page.keyboard.press('Escape');
      await page.getByRole('button',{name:'Export preview',exact:true}).click();
      const exported=await page.locator('.export-preview').innerText();
      assert.match(exported,/State: Background service is stopped/);
      assert.match(exported,/Authentication: Historical evidence only/);
      assert.doesNotMatch(exported,/State: Time sync active/);
      await page.keyboard.press('Escape');
      await openSettings();
      await submit('start'); await deliver();
      assert.match(await response.innerText(),/Running · fresh agreement required/);
      await page.locator('.app-nav [data-value="status"]').click();
      assert.match(await page.locator('#state-title').innerText(),/Reacquiring time/);
      await page.getByRole('button',{name:'Simple',exact:true}).click();
      assert.match(await page.locator('#page-title').innerText(),/Reacquiring time/);
      assert.doesNotMatch(await page.locator('main').innerText(),/being kept in sync automatically/);
      await page.getByRole('button',{name:'Power user',exact:true}).click();
      await openSettings();
      assert.equal(await operation('stop').isDisabled(),true);
      assert.equal(await operation('restart').isDisabled(),true);
      await page.goto(`http://127.0.0.1:${server.address().port}/${file}`);
      await page.getByRole('button',{name:'Power user',exact:true}).click();
      await page.locator('.app-nav [data-value="diagnostics"]').click();
      if(!(await page.locator('#reviewer-controls').evaluate(e=>e.open))) await page.locator('#reviewer-controls > summary').click();
      await page.locator('#sample-log-service-response').selectOption('active');
      await page.getByRole('button',{name:'Preview temporary collection',exact:true}).click();
      await page.locator('#sample-log-scope').selectOption('service');
      await page.getByRole('button',{name:'Start example',exact:true}).click();
      assert.match(await page.locator('#sample-log-result').innerText(),/Sample response · Active/);
      await page.keyboard.press('Escape');
      await openSettings(); await choose('confirmed'); await submit('restart'); await deliver();
      assert.match(await response.innerText(),/fresh agreement required/);
      await page.locator('.app-nav [data-value="diagnostics"]').click();
      assert.match(await page.locator('.sample-log-summary').innerText(),/Ended by service operation/);
      assert.doesNotMatch(await page.locator('.sample-log-summary').innerText(),/Sample DEBUG active/);
      await page.goto(`http://127.0.0.1:${server.address().port}/${file}`);
      await page.locator('.app-nav [data-value="settings"]').click();
      await page.getByRole('button',{name:'Manage service in Power user',exact:true}).click();
      await choose('unknown'); await submit('stop'); await deliver();
      assert.match(await response.innerText(),/Outcome unknown/);
      assert.equal(await controls().evaluateAll(nodes=>nodes.every(n=>n.disabled)),true);
      assert.match(await page.locator('.service-facts').innerText(),/Unknown · reconcile current ownership/);
      await page.getByRole('button',{name:'Diagnose',exact:true}).click();
      assert.match(await page.locator('#service-diagnosis').innerText(),/Outcome unknown/);
      await page.getByRole('button',{name:'Preview temporary collection',exact:true}).click();
      await page.locator('#sample-log-scope').selectOption('service');
      assert.equal(await page.getByRole('button',{name:/^Start example/}).isDisabled(),true);
      await page.locator('#sample-log-scope').selectOption('both');
      await page.getByRole('button',{name:'Start example',exact:true}).click();
      assert.match(await page.locator('#sample-log-result').innerText(),/Sample response · Unconfirmed/);
      assert.match(await page.locator('#sample-log-result').innerText(),/Unknown · service response not received/);
      await page.keyboard.press('Escape');
      if(screenshotDir) await page.screenshot({path:path.join(screenshotDir,`${file.startsWith('index')?'local':'standalone'}-unknown-diagnosis-${width}.png`),fullPage:true});
      assert.equal(await page.locator('dialog').count(),0);
      assert.equal(await page.evaluate(()=>JSON.stringify(window.NevroTickModel.getScenario('healthy'))),fixtureSnapshot);
      assert.equal(await page.locator('body').evaluate(e=>e.scrollWidth<=innerWidth),true,`${file} overflow ${width}`);
      await page.goto(`http://127.0.0.1:${server.address().port}/${file}?scene=service-stopped`);
      await page.locator('.app-nav [data-value="settings"]').click();
      await page.getByRole('button',{name:'Manage service in Power user',exact:true}).click();
      assert.equal(await operation('start').isEnabled(),true);
      await operation('start').click();
      assert.match(await page.locator('dialog').innerText(),/Start is read-only/);
      await page.locator('dialog [data-action="service-confirm"]').click();
      await choose('confirmed'); await deliver();
      assert.match(await response.innerText(),/Startup remains read-only/);
      assert.equal(await operation('restart').isDisabled(),true);
      assert.equal(await operation('stop').isDisabled(),true);
      await page.goto(`http://127.0.0.1:${server.address().port}/${file}?scene=stale`);
      await page.locator('.app-nav [data-value="settings"]').click();
      await page.getByRole('button',{name:'Manage service in Power user',exact:true}).click();
      assert.equal(await controls().evaluateAll(nodes=>nodes.every(n=>n.disabled)),true);
      assert.match(await page.locator('.service-facts').innerText(),/disconnected status channel does not prove/);
      assert.equal(await page.getByRole('button',{name:'Diagnose',exact:true}).isEnabled(),true);
      assert.deepEqual(errors,[]); assert.deepEqual(external,[]);
      results.push({file,width,checks:'cancel + focus; UAC cancel; pre-effect failure; pending dedup/navigation/reset; stop/start/restart/unknown; all evidence pages/export; read-only Start; disconnection; raw fixture preserved',pageErrors:0,externalRequests:0});
      await page.close();
    }
    console.log(JSON.stringify(results,null,2));
  }finally{await browser.close();server.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
