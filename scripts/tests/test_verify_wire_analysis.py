    def exercise_wire_runner(self, exercise, *, runtime_output="inert runtime result"):
        """Reach execute's actual nested runner with private inert metadata/tools.

        Product/tool/vendor admission is stubbed; source copies, digest guards,
        COMMON command/result guards and runner option forwarding stay real.
        No Rust, Cargo or installed analyzer is executed by these unit controls.
        """
        with tempfile.TemporaryDirectory() as temporary:
            scratch = Path(temporary).resolve()
            checkout, vendor = scratch / "checkout", scratch / "vendor"
            checkout.mkdir(); vendor.mkdir()
            stable, payload = scratch / "stable", scratch / "payload"
            stable.mkdir(); payload.mkdir()
            extra = (MODULE.POLICY, "scripts/portable-analysis.py", "scripts/verify-wire-analysis.py",
                     "scripts/prepare-product.py", "scripts/analysis-runtime.py", "scripts/check-analysis.py",
                     "policy/analysis-tools.json", "policy/verification-manifest.toml", "fixture/target.rs", "fixture/NOTICE")
            for relative in (*extra, ".cargo/mutants.toml", MODULE.NTS_KE):
                path = checkout / relative
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text('additional_cargo_args=["--frozen"]\ncap_lints=false\n'
                                if relative == ".cargo/mutants.toml" else "inert runner input\n")
            identity = {relative: MODULE.PRODUCT.sha256(checkout / relative)
                        for relative in (".cargo/mutants.toml", MODULE.NTS_KE)}
            origin = scratch / "cargo-mutants"; origin.write_text("inert extension bytes")
            policy = {"mutation_jobs": 10, "mutation_process_limit": 512, "mutation_message_format": "json",
                      "coverage_guided_fuzzing": {"target_source": "fixture/target.rs", "llvm_notice": "fixture/NOTICE"}}
            admitted = {"base": payload, "stable": stable, "policy_sha256": "a" * 64, "inventories": []}
            args = SimpleNamespace(lane="mutation", subject="nts_ke", vendor_dir=vendor,
                                   output_dir=scratch / "output")
            result = {"exit_code": 0, "failure": None, "output": runtime_output}
            def lanes(_scope, _subjects, _policy, _work, tools, run, _report, lane):
                self.assertEqual(lane, "mutation")
                exercise(run, tools, runtime, stable)
            with (patch.object(MODULE, "ROOT", checkout),
                  patch.object(MODULE, "read_policy", return_value=policy),
                  patch.object(MODULE.PRODUCT, "admit_product", return_value=({}, identity)),
                  patch.object(MODULE.ANALYSIS, "admit", return_value=admitted),
                  patch.object(MODULE.PRODUCT, "admit_vendor", return_value={}),
                  patch.object(MODULE, "require_current_candidate"),
                  patch.object(MODULE, "tool_path", return_value=origin),
                  patch.object(MODULE.RUNTIME, "run", return_value=result) as runtime,
                  patch.object(MODULE.COMMON, "run_analysis_lanes", side_effect=lanes)):
                MODULE.execute(args, {})

