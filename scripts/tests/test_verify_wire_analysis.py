    @staticmethod
    def vendor_fixture(root):
        """Build inert literal source/archive neighbors without executing Rust."""
        import hashlib
        import io
        import tarfile
        source = root / "cache"
        (source / "src").mkdir(parents=True)
        files = {"Cargo.toml": b'[package]\nname="fixture"\nversion="0.0.1"\n',
                 "src/lib.rs": b"pub const VALUE: u32 = 7;\n"}
        archive = root / "fixture.crate"
        with tarfile.open(archive, "w:gz") as stream:
            for name, contents in files.items():
                (source / name).write_bytes(contents)
                member = tarfile.TarInfo("fixture-0.0.1/" + name)
                member.size = len(contents)
                stream.addfile(member, io.BytesIO(contents))
        (source / ".cargo-ok").write_text("Cargo cache marker")
        return source, archive, {"name": "fixture", "version": "0.0.1",
                                 "checksum": hashlib.sha256(archive.read_bytes()).hexdigest()}

