            for bad in invalid:
                with self.subTest(files=bad):
                    path.write_text(json.dumps({**policy, "critical_files": bad}))
                    with self.assertRaises(MODULE.Incomplete):
                        MODULE.read_policy(root)
            path.write_text(json.dumps(policy))
            for critical, security in [(owners[:-1], owners), (owners, owners[:-1])]:
                manifest_path.write_text(manifest(critical, security))
                with self.assertRaises(MODULE.Incomplete):
                    MODULE.read_policy(root)

