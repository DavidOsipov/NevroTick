    def test_multifile_mutation_accounting_stays_per_file_and_capped(self):
        """Each file has its own viable denominator; an average cannot rescue a file."""
        inventories = {}
        for name, filename in MODULE.SUBJECTS.items():
            items = [{"name": filename + ":fault", "file": filename, "package": "ntp-wire"}]
            inventory = MODULE.mutation_inventory(items, 512, filename)
            inventories[name] = inventory
            report = {"cargo_mutants_version": "27.1.0", "total_mutants": 1, "outcomes": [
                {"scenario": "Baseline", "summary": "Success"},
                {"scenario": {"Mutant": items[0]}, "summary": "CaughtMutant",
                 "phase_results": [{"phase": "Test"}]}]}
            report = complete_report(report)
            self.assertEqual(MODULE.mutation_counts(report, inventory, filename)["file"], filename)
            other = MODULE.DATAGRAM if filename == MODULE.HEADER else MODULE.HEADER
            with self.assertRaises(MODULE.Incomplete):
                MODULE.mutation_counts(report, inventory, other)
            missed = json.loads(json.dumps(report)); missed["outcomes"][1]["summary"] = "MissedMutant"
            with self.assertRaises(MODULE.Incomplete):
                MODULE.mutation_counts(missed, inventory, filename)
        self.assertEqual(MODULE.combined_mutant_count(inventories, 2), 2)
        for bad, cap in (({}, 512), (inventories, 1)):
            with self.assertRaises(MODULE.Incomplete):
                MODULE.combined_mutant_count(bad, cap)
        with self.assertRaises(MODULE.Incomplete):
            MODULE.mutation_inventory([*inventories["header"].values(), *inventories["datagram"].values()],
                                      512, MODULE.HEADER)

