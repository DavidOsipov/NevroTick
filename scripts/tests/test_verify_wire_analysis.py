    def test_wire_campaign_uses_policy_workers_and_private_runtime_profile(self):
        def exercise(run, tools, runtime, stable):
            command = self.nts_ke_campaign_argv(tools, 10)
            result = run("mutation-campaign:nts_ke", command, 30, mutation_subject="nts_ke")
            self.assertEqual(result, {"exit_code": 0, "failure": None, "output": "inert runtime result"})
            mutation = runtime.call_args.kwargs
            self.assertEqual((mutation["build_jobs"], mutation["cargo_target_mode"], mutation["process_limit"]),
                             (1, "worker", 512))
            self.assertEqual(mutation["environment"]["RUST_TEST_THREADS"], "1")
            ordinary = run("contract-library", [str(stable / "bin/rustc"), "fixture.rs"], 30)
            self.assertEqual(ordinary, "inert runtime result")
            contract = runtime.call_args.kwargs
            self.assertEqual(contract["build_jobs"], 12)
            self.assertEqual(contract["environment"]["RUST_TEST_THREADS"], "12")
            # Omitting both options retains the qualified shared/128 defaults.
            self.assertNotIn("cargo_target_mode", contract)
            self.assertNotIn("process_limit", contract)
            self.assertEqual(runtime.call_count, 2)
        self.exercise_wire_runner(exercise)

