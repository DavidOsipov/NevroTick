from __future__ import annotations

import hashlib
import importlib.util
import json
from pathlib import Path
import stat
import tempfile
import tomllib
import unittest


HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
SPEC = importlib.util.spec_from_file_location("era_constructor_projection_test", HERE / "era_constructor_projection.py")
PROJECTION = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(PROJECTION)


class PreparationTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory(prefix="nevrotick-era-constructor-preparation-")
        self.addCleanup(self.temporary.cleanup)
        self.base = Path(self.temporary.name)
        self.source = self.base / "source"
        for name in PROJECTION.SOURCE_SHA256:
            destination = self.source / name
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_bytes((ROOT / name).read_bytes())
        self.inputs = self.base / "inputs"
        self.harness = HERE / "era_constructor_harness.rs"

    def prepare(self, case="healthy", **kwargs):
        return PROJECTION.prepare_era_constructor(self.source, self.inputs, case, self.harness, **kwargs)

    def test_complete_actual_modules_and_real_derive_remain_unchanged(self):
        result = self.prepare()
        for name in ("era.rs", "coordinate.rs"):
            self.assertEqual((self.inputs / "src" / name).read_bytes(),
                             (self.source / "crates/time-domain/src" / name).read_bytes())
        self.assertEqual((self.inputs / "src/proof.rs").read_bytes(), self.harness.read_bytes())
        era = (self.inputs / "src/era.rs").read_text()
        self.assertIn("#[derive(Validate)]", era)
        self.assertIn(".validate()", era)
        self.assertIn("fn endpoint_rule", era)
        self.assertIn("pub fn new(earliest: i128, latest: i128)", era)
        library = (self.inputs / "src/lib.rs").read_text()
        self.assertIn("pub enum DomainError", library)
        self.assertIn("#[cfg(kani)]\nmod proof;", library)
        self.assertNotIn("mod garde", library)
        self.assertTrue(result["complete_era_module_preserved"])
        self.assertEqual(result["input_assumptions"], [])

    def test_exact_minimal_lock_and_offline_real_dependency_config(self):
        result = self.prepare()
        manifest = tomllib.loads((self.inputs / "Cargo.toml").read_text())
        self.assertEqual(manifest["dependencies"], {"garde": PROJECTION.GARDE_DEPENDENCY})
        self.assertEqual(manifest["workspace"], {})
        actual = tomllib.loads((ROOT / "Cargo.toml").read_text())["workspace"]["package"]
        for key in ("edition", "rust-version", "license", "repository"):
            self.assertEqual(manifest["package"][key], actual[key])
        original = tomllib.loads((ROOT / "Cargo.lock").read_text())["package"]
        pinned = {package["name"]: package for package in original if package["name"] in PROJECTION.GRAPH_VERSIONS}
        generated = tomllib.loads((self.inputs / "Cargo.lock").read_text())["package"]
        self.assertEqual({package["name"]: package for package in generated
                          if package["name"] != PROJECTION.PACKAGE_NAME}, pinned)
        self.assertEqual(len(generated), 15)
        config = tomllib.loads((self.inputs / ".cargo/config.toml").read_text())
        self.assertTrue(config["net"]["offline"])
        self.assertEqual(config["source"]["crates-io"]["replace-with"], "formal-vendor")
        self.assertNotIn("rustflags", str(config))
        self.assertFalse(result["vendor"]["admitted"])
        self.assertFalse(result["vendor"]["metadata_observed"])
        graph = {package["name"]: package for package in result["registry_graph"]}
        self.assertEqual(graph["garde"]["expected_features"], ["derive"])
        self.assertEqual(graph["compact_str"]["expected_features"], [])
        self.assertEqual(graph["smallvec"]["expected_features"], [])
        for package in graph.values():
            self.assertEqual(len(package["retained_inventory"]["files_sha256"]), 64)
        self.assertFalse(result["shipping_graph_qualified"])
        self.assertFalse(result["workspace_lints_and_build_config_preserved"])

    def test_lock_uses_cargo_canonical_serialization_without_changing_graph(self):
        self.prepare()
        data = (self.inputs / "Cargo.lock").read_bytes()
        self.assertTrue(data.startswith(
            b"# This file is automatically @generated by Cargo.\n"
            b"# It is not intended for manual editing.\nversion = 4\n\n"
        ))
        packages = tomllib.loads(data.decode())["package"]
        names = [package["name"] for package in packages]
        self.assertEqual(names, sorted(names))
        root_block = (b'[[package]]\nname = "nevrotick-era-constructor-proof"\n'
                      b'version = "0.0.0"\ndependencies = [\n "garde",\n]\n')
        self.assertIn(root_block, data)
        self.assertTrue(data.endswith(b"\n"))
        self.assertFalse(data.endswith(b"\n\n"))
        original = tomllib.loads((ROOT / "Cargo.lock").read_text())["package"]
        external = {p["name"]: p for p in original if p["name"] in PROJECTION.GRAPH_VERSIONS}
        self.assertEqual({p["name"]: p for p in packages if p["name"] != PROJECTION.PACKAGE_NAME}, external)

    def test_source_seal_hashes_modes_and_explicit_unqualified_prerequisites(self):
        result = self.prepare()
        for name, expected in result["generated_files_sha256"].items():
            path = self.inputs / name
            self.assertEqual(hashlib.sha256(path.read_bytes()).hexdigest(), expected)
            self.assertEqual(stat.S_IMODE(path.stat().st_mode), 0o400)
        for directory in (self.inputs, self.inputs / "src", self.inputs / ".cargo"):
            self.assertEqual(stat.S_IMODE(directory.stat().st_mode), 0o500)
        receipt_bytes = (self.inputs / "correspondence.json").read_bytes()
        receipt = json.loads(receipt_bytes)
        self.assertEqual(result["correspondence_sha256"], hashlib.sha256(receipt_bytes).hexdigest())
        self.assertEqual(receipt["entrypoint"], "Cargo.toml")
        self.assertFalse(receipt["cargo_mode_admitted"])
        self.assertFalse(receipt["native_profile_qualified"])
        self.assertEqual(receipt["native_commands_executed"], 0)
        self.assertIsNone(receipt["unwind_bound"])
        prerequisites = " ".join(receipt["prerequisites"])
        for required in ("proc macros", "build scripts", "Unwind 1", "--no-malloc-may-fail",
                         "--edition", "--locked/--frozen", "code-generation-only", "namespace"):
            self.assertIn(required, prerequisites)

    def test_compile_only_candidate_has_versioned_source_evidence_without_execution(self):
        evidence = self.prepare()["kani_source_evidence"]
        self.assertEqual(evidence["version"], "0.68.0")
        self.assertEqual(evidence["ref"], "kani-0.68.0")
        arguments = evidence["compile_only_candidate_argv"]
        self.assertEqual(arguments[1], "kani")
        for required in ("--manifest-path", "--lib", "--only-codegen", "--target-dir"):
            self.assertIn(required, arguments)
        for incompatible in ("--export-json", "--locked", "--frozen", "--edition", "--jobs"):
            self.assertNotIn(incompatible, arguments)
        self.assertFalse(evidence["candidate_argv_executed"])
        for key in ("compile_only_argument", "compile_only_skips_verification",
                    "compile_only_rejects_json_export", "cargo_mode_argv1_dispatch"):
            self.assertIn("/blob/kani-0.68.0/kani-driver/src/", evidence[key])

    def test_source_or_lock_drift_rejected_before_output_creation(self):
        for name in PROJECTION.SOURCE_SHA256:
            path = self.source / name
            original = path.read_bytes()
            path.write_bytes(original + b"\n# drift\n")
            with self.subTest(name=name), self.assertRaisesRegex(ValueError, "complete source changed"):
                self.prepare()
            self.assertFalse(self.inputs.exists())
            path.write_bytes(original)

    def test_controls_change_only_one_actual_expression_and_preserve_garde(self):
        original = (self.source / "crates/time-domain/src/era.rs").read_bytes()
        for case, mutation in PROJECTION.CONTROLS.items():
            with self.subTest(case=case):
                folder = self.base / case
                result = PROJECTION.prepare_era_constructor(self.source, folder, case, self.harness)
                self.assertEqual(original.count(mutation["before"].encode()), 1)
                self.assertEqual((folder / "src/era.rs").read_bytes(), original.replace(
                    mutation["before"].encode(), mutation["after"].encode(), 1))
                self.assertIn(b"#[derive(Validate)]", (folder / "src/era.rs").read_bytes())
                self.assertIn(b".validate()", (folder / "src/era.rs").read_bytes())
                self.assertFalse(result["complete_era_module_preserved"])
                self.assertEqual(result["mutation"], mutation)

    def test_unknown_control_and_existing_project_preserve_inputs(self):
        with self.assertRaisesRegex(ValueError, "Unknown"):
            self.prepare("fake_validation")
        self.assertFalse(self.inputs.exists())
        self.inputs.mkdir()
        (self.inputs / "evidence.txt").write_bytes(b"preserved")
        with self.assertRaisesRegex(ValueError, "overwrite"):
            self.prepare()
        self.assertEqual((self.inputs / "evidence.txt").read_bytes(), b"preserved")

    def test_full_raw_harness_schedule_and_declared_assertions_covers(self):
        text = self.harness.read_text()
        self.assertEqual(text.count("kani::any::<i128>()"), 2)
        self.assertNotIn("kani::assume", text)
        self.assertNotIn("EraWindow {", text)
        self.assertIn("EraWindow::new(earliest, latest)", text)
        jobs = PROJECTION.schedule()
        self.assertEqual([job["case"] for job in jobs], [
            "healthy", "reject_singleton", "swap_retained_endpoints", "wrong_validation_error", "healthy"])
        self.assertFalse(jobs[0]["restored_healthy"])
        self.assertTrue(jobs[-1]["restored_healthy"])
        self.assertEqual(len({job["intended_failure"] for job in jobs[1:-1]}), 3)
        for label in (*PROJECTION.REQUIRED_ASSERTIONS["proof::era_constructor_full_domain"],
                      *PROJECTION.REQUIRED_COVERS["proof::era_constructor_full_domain"]):
            self.assertIn('"' + label + '"', text)

    def test_registry_closure_rejects_missing_extra_and_unpinned_sources(self):
        original = (ROOT / "Cargo.lock").read_text()
        for modified in (original.replace('name = "unicode-ident"', 'name = "missing-ident"'),
                         original.replace(' "smallvec",', ' "getrandom",'),
                         original.replace(PROJECTION.REGISTRY, "registry+https://other.invalid/index")):
            with self.subTest(modified=modified[-80:]), self.assertRaises(ValueError):
                PROJECTION.selected_registry_graph(modified.encode())

    def metadata_fixture(self):
        """Tiny metadata records model preparation parsing, never executable Garde."""
        graph, _ = PROJECTION.selected_registry_graph((ROOT / "Cargo.lock").read_bytes())
        vendor = self.base / "vendor"
        vendor.mkdir()
        for package in graph:
            directory = vendor / (package["name"] + "-" + package["version"])
            directory.mkdir()
            manifest = (f'[package]\nname = {json.dumps(package["name"])}\n'
                        f'version = {json.dumps(package["version"])}\n'
                        f'license = {json.dumps(package["license"])}\n')
            if package["build_script"]:
                manifest += 'build = ' + json.dumps(package["build_script"]) + '\n'
            if package["proc_macro"]:
                manifest += '\n[lib]\nproc-macro = true\n'
            data = manifest.encode()
            (directory / "Cargo.toml").write_bytes(data)
            (directory / ".cargo-checksum.json").write_text(json.dumps({
                "package": package["checksum"], "files": {"Cargo.toml": hashlib.sha256(data).hexdigest()}}))
        return vendor, graph

    def test_optional_metadata_observation_does_not_claim_payload_admission(self):
        vendor, graph = self.metadata_fixture()
        result = self.prepare(vendor_root=vendor)
        observation = result["vendor"]
        self.assertTrue(observation["metadata_observed"])
        self.assertEqual(len(observation["packages"]), len(graph))
        self.assertFalse(observation["payload_files_hashed"])
        self.assertFalse(observation["admitted"])
        self.assertIn("not a trusted whole-source inventory", observation["limit"])

    def test_optional_metadata_mismatch_or_alias_rejects_before_output(self):
        vendor, graph = self.metadata_fixture()
        directory = vendor / (graph[0]["name"] + "-" + graph[0]["version"])
        metadata = directory / ".cargo-checksum.json"
        data = json.loads(metadata.read_text())
        data["package"] = "0" * 64
        metadata.write_text(json.dumps(data))
        with self.assertRaisesRegex(ValueError, "checksum metadata mismatch"):
            self.prepare(vendor_root=vendor)
        self.assertFalse(self.inputs.exists())
        alias = self.base / "alias"
        alias.symlink_to(vendor, target_is_directory=True)
        with self.assertRaisesRegex(ValueError, "canonical"):
            self.prepare(vendor_root=alias)
        self.assertFalse(self.inputs.exists())


class IndependentContractFacts(unittest.TestCase):
    def test_signed_word_and_fraction_envelope_and_neighbors(self):
        lower = -(2**63) * 2**32
        upper = (2**63 - 1) * 2**32 + (2**32 - 1)
        self.assertEqual(lower, -39_614_081_257_132_168_796_771_975_168)
        self.assertEqual(upper, 39_614_081_257_132_168_796_771_975_167)
        self.assertLess(-(2**127), lower - 1)
        self.assertLess(upper + 1, 2**127 - 1)
        self.assertTrue(lower <= 0 <= upper)


